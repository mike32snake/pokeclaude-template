#!/usr/bin/env python3
"""Generate src/server/widths.js from the Unicode database Python already ships.

Column accounting is the fiddliest part of a terminal emulator and the one that breaks
screen parsing when it is wrong: one mis-measured emoji shifts every column after it,
and composerRegion stops finding the box. So the ranges are DERIVED, not typed.
"""
import sys, unicodedata

def width(cp):
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cat in ('Mn', 'Me'):          # combining marks sit on the previous cell
        return 0
    if cat == 'Cf' and cp != 0x00AD: # format controls: ZWJ, ZWNJ, directional marks
        return 0
    if 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF:   # variation selectors
        return 0
    if cp == 0x200B:
        return 0
    if unicodedata.east_asian_width(ch) in ('W', 'F'):
        return 2
    return 1

def ranges(want):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:   # surrogates never appear as codepoints
            continue
        w = width(cp) if unicodedata.category(chr(cp)) != 'Cn' else 1
        if w == want:
            if start is None: start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev)); start = None
    if start is not None: out.append((start, prev))
    return out

zero, wide = ranges(0), ranges(2)
def fmt(rs):
    return ','.join(f'0x{a:x},0x{b:x}' for a, b in rs)

print(f"generated {len(zero)} zero-width ranges, {len(wide)} wide ranges", file=sys.stderr)
open('src/server/widths.js', 'w').write(f'''// Generated by tools/gen-widths.py from Python's Unicode database. Do not hand-edit;
// regenerate it. Column accounting is what breaks screen parsing when it is wrong: one
// mis-measured emoji shifts every column after it and composerRegion stops finding the
// composer, so these ranges are derived from the Unicode data rather than typed out.
//
// Flat sorted [lo, hi, lo, hi, ...] pairs, binary-searched. A codepoint in ZERO takes
// no cell (combining marks, ZWJ, variation selectors); one in WIDE takes two.
const ZERO = new Uint32Array([{fmt(zero)}]);
const WIDE = new Uint32Array([{fmt(wide)}]);

function inRanges(t, cp) {{
  let lo = 0, hi = (t.length >> 1) - 1;
  while (lo <= hi) {{
    const mid = (lo + hi) >> 1, i = mid << 1;
    if (cp < t[i]) hi = mid - 1;
    else if (cp > t[i + 1]) lo = mid + 1;
    else return true;
  }}
  return false;
}}

// How many cells a codepoint occupies. Control characters never reach here: the parser
// takes them before the grid does.
export function charWidth(cp) {{
  if (cp < 0x7f) return cp < 0x20 ? 0 : 1;      // ASCII fast path, the overwhelming case
  if (inRanges(ZERO, cp)) return 0;
  return inRanges(WIDE, cp) ? 2 : 1;
}}
''')
